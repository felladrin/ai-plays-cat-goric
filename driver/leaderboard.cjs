// Render the leaderboard from the committed results: every docs/leaderboard/<version>/*.json
// is one model's benchmark.json for that version. The tables go between the
// leaderboard markers in readme.md (one row per model) and docs/benchmark.md (one
// row per model with each seed's outcome), newest version first.
//
//   node leaderboard.cjs            (from driver/; npm run leaderboard) rewrites both tables
//   node leaderboard.cjs --check    exits 1 when a table is out of date (npm test runs it)
"use strict";

const fs = require("fs");
const path = require("path");
const { score, DEFAULT_SEEDS, LEVELS } = require("./benchmark.cjs");

const ROOT = path.join(__dirname, "..");
const DATA = path.join(ROOT, "docs", "leaderboard");
const START = "<!-- leaderboard:start (generated by driver/leaderboard.cjs; edit docs/leaderboard/ instead) -->";
const END = "<!-- leaderboard:end -->";

// The entries of each version, newest version first, each checked to be a full
// benchmark of that version on the leaderboard seeds. params.json holds each model's
// parameter count, since a name does not always say it.
function load(dir = DATA) {
  const params = JSON.parse(fs.readFileSync(path.join(dir, "params.json"), "utf8"));
  const versions = fs.readdirSync(dir).filter((v) => /^v\d+$/.test(v)).sort((a, b) => b.slice(1) - a.slice(1));
  return versions.map((version) => {
    const entries = fs.readdirSync(path.join(dir, version)).filter((f) => f.endsWith(".json")).map((f) => {
      const b = JSON.parse(fs.readFileSync(path.join(dir, version, f), "utf8"));
      const where = `docs/leaderboard/${version}/${f}`;
      if (b.version !== version) throw new Error(`${where}: version is ${b.version}, not ${version}`);
      const seeds = b.results.map((r) => String(r.seed));
      if (seeds.join(" ") !== DEFAULT_SEEDS.join(" ")) throw new Error(`${where}: seeds ${seeds.join(" ")}, not ${DEFAULT_SEEDS.join(" ")}`);
      if (!Number.isInteger(params[name(b)])) throw new Error(`${where}: no parameter count for ${name(b)} in docs/leaderboard/params.json`);
      return Object.assign({ file: f, score: score(b.results), params: params[name(b)] }, b);
    });
    return { version, entries };
  });
}

// Best first: more seeds won, then more levels cleared, then fewer deaths.
const better = (a, b) => {
  const d = (e) => (e.score.medianDeaths === null ? Infinity : e.score.medianDeaths);
  return b.score.pass1 - a.score.pass1 || b.score.levelsCleared - a.score.levelsCleared || d(a) - d(b);
};
function rank(entries) {
  return entries.slice().sort(better);
}

// Equal scores share a rank number, the next one skips (1, 2, 2, 4).
const place = (ranked, i) => 1 + ranked.filter((o) => better(o, ranked[i]) < 0).length;

const pct = (x) => `${Math.round(x * 100)}%`;
const name = (e) => e.model.replace(/^.*\//, "");
const size = (n) => (n >= 1e9 ? `${(n / 1e9).toFixed(1)}B` : `${Math.round(n / 1e6)}M`);

function summaryTable(versions) {
  return versions.map(({ version, entries }) => [
    `**${version}**`,
    "",
    "| Rank | Model | Params | pass@1 | pass@5 | Levels cleared | Deaths |",
    "| --- | --- | --- | --- | --- | --- | --- |",
    ...rank(entries).map((e, i, ranked) => `| ${place(ranked, i)} | ${name(e)} | ${size(e.params)} | ${pct(e.score.pass1)} | ${e.score.pass5 ? "yes" : "no"} | ` +
      `${e.score.levelsCleared.toFixed(1)} / ${LEVELS} | ${e.score.medianDeaths === null ? "n/a" : e.score.medianDeaths} |`),
  ].join("\n")).join("\n\n");
}

function seedTable(versions) {
  return versions.map(({ version, entries }) => [
    `**${version}**`,
    "",
    `| Model | ${DEFAULT_SEEDS.map((s) => `Seed ${s}`).join(" | ")} |`,
    `| --- | ${DEFAULT_SEEDS.map(() => "---").join(" | ")} |`,
    ...rank(entries).map((e) => `| ${name(e)} | ${e.results.map((r) =>
      r.won ? `won, ${r.totalDeaths} deaths` : `lost on L${r.lastLevel}, ${r.totalDeaths} deaths`).join(" | ")} |`),
  ].join("\n")).join("\n\n");
}

// The file with its marked block replaced by `table`.
function splice(text, table, file) {
  const a = text.indexOf(START);
  const b = text.indexOf(END);
  if (a < 0 || b < a) throw new Error(`${file}: the leaderboard markers are missing`);
  return text.slice(0, a + START.length) + "\n" + table + "\n" + text.slice(b);
}

function main(argv) {
  const check = argv.includes("--check");
  const versions = load().filter((v) => v.entries.length);
  const none = "_No results yet._";
  let stale = 0;
  for (const [rel, table] of [["readme.md", versions.length ? summaryTable(versions) : none],
                              ["docs/benchmark.md", versions.length ? seedTable(versions) : none]]) {
    const file = path.join(ROOT, rel);
    const text = fs.readFileSync(file, "utf8");
    const next = splice(text, table, rel);
    if (next === text) continue;
    if (check) { console.error(`${rel}: the leaderboard is out of date; run npm run leaderboard in driver/`); stale++; }
    else { fs.writeFileSync(file, next); console.log(`${rel}: leaderboard updated`); }
  }
  if (stale) process.exit(1);
}

if (require.main === module) main(process.argv.slice(2));

module.exports = { load, rank, summaryTable, seedTable, splice, START, END };
